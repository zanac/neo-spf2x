"""Generates schematics (.kicad_sch), netlist check, ball assignment CSV and LPF for the 4 boards."""
import csv, os, sys
import boards, kisch, selftest_sch

OUT = os.path.join(os.path.dirname(__file__), "..", "out")


def main():
    os.makedirs(OUT, exist_ok=True)
    rc = 0
    for fmt in ("aes", "mvs"):
        cha, assign = boards.build_cha(fmt)
        prog = boards.build_prog(fmt)
        for name, d in ((f"{fmt}_cha", cha), (f"{fmt}_prog", prog)):
            p = os.path.join(OUT, name + ".kicad_sch")
            kisch.write(d, p, name.upper().replace("_", " "))
            bad = selftest_sch.check(d)
            print(name, "schematic", "round-trip OK" if not bad else f"MISMATCH {bad[:5]}")
            rc |= bool(bad)
        with open(os.path.join(OUT, f"{fmt}_fpga_pins.csv"), "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["net", "ball"])
            for k, v in sorted(assign.items()):
                w.writerow([k, v])
        with open(os.path.join(OUT, f"{fmt}_cha.lpf"), "w") as f:
            f.write("# generated by hardware/gen/build_sch.py: net -> ball (LVCMOS33)\n")
            for k, v in sorted(assign.items()):
                f.write(f'LOCATE COMP "{k}" SITE "{v}";\nIOBUF PORT "{k}" IO_TYPE=LVCMOS33;\n')
    return rc


if __name__ == "__main__":
    sys.exit(main())
