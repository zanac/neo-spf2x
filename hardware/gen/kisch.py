"""Writes a KiCad 7 schematic (.kicad_sch) from a Design.  Every pin gets a net label at its
connection point (or a no-connect flag), so connectivity is exactly the Design netlist."""
import math
import re
import uuid

import kilib

GRID = 2.54


def uid():
    return str(uuid.uuid4())


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def sym_text(sym, design):
    """Embedded lib symbol text (name = full lib id) and parsed pin geometry."""
    if sym in design.custom_symbols:
        return custom_text(sym, design.custom_symbols[sym])
    lib, name = sym.split(":", 1)
    b = kilib.resolve(lib, name)
    b = b.replace('(symbol "%s"' % name, '(symbol "%s"' % sym, 1)
    return b


def custom_text(sym, spec):
    name = sym.split(":", 1)[1]
    out = [f'(symbol {q(sym)} (pin_names (offset 1.016)) (in_bom yes) (on_board yes)',
           f'  (property "Reference" {q(spec.get("ref", "U"))} (at 0 0 0) (effects (font (size 1.27 1.27))))',
           f'  (property "Value" {q(name)} (at 0 -2 0) (effects (font (size 1.27 1.27))))',
           '  (property "Footprint" "" (at 0 0 0) (effects (font (size 1.27 1.27)) hide))',
           '  (property "Datasheet" "" (at 0 0 0) (effects (font (size 1.27 1.27)) hide))']
    for u, upins in sorted(spec["units"].items()):
        left = [p for p in upins if p["side"] == "L"]
        right = [p for p in upins if p["side"] == "R"]
        n = max(len(left), len(right), 1)
        h = n * 2.54 / 2 + 1.27
        w = spec.get("width", 20.32)
        out.append(f'  (symbol {q(name + "_%d_1" % u)}')
        out.append(f'    (rectangle (start {-w/2:.2f} {h:.2f}) (end {w/2:.2f} {-h:.2f}) '
                   '(stroke (width 0.254) (type default)) (fill (type background)))')
        for side, pl in (("L", left), ("R", right)):
            for i, p in enumerate(pl):
                y = (len(pl) - 1) * 2.54 / 2 - i * 2.54
                x = -w / 2 - 5.08 if side == "L" else w / 2 + 5.08
                ang = 0 if side == "L" else 180
                out.append(f'    (pin {p["etype"]} line (at {x:.2f} {y:.2f} {ang}) (length 5.08) '
                           f'(name {q(p["name"])} (effects (font (size 1 1)))) '
                           f'(number {q(p["number"])} (effects (font (size 1 1)))))')
        out.append("  )")
    out.append(")")
    return "\n".join(out)


def block(s, start):
    return kilib.block(s, start)


def parse_pins(text):
    """-> list of dict(number, x, y, angle, unit) from an embedded symbol text."""
    res = []
    for sm in re.finditer(r'\(symbol "[^"]*_(\d+)_(\d+)"', text):
        unit = int(sm.group(1))
        sb = block(text, sm.start())
        for pm in re.finditer(r"\(pin \w+ \w+ \(at ([-\d.]+) ([-\d.]+) (\d+)\)", sb):
            pb = block(sb, pm.start())
            num = re.search(r'\(number "([^"]*)"', pb).group(1)
            res.append(dict(number=num, x=float(pm.group(1)), y=float(pm.group(2)),
                            angle=int(pm.group(3)), unit=unit))
    return res


def write(design, path, title="", paper=(1189, 841)):
    root = uid()
    syms = {}
    for p in design.parts.values():
        if p.sym not in syms:
            t = sym_text(p.sym, design)
            syms[p.sym] = (t, parse_pins(t))
    out = ['(kicad_sch (version 20230121) (generator ngsd_gen)', f'  (uuid {root})',
           f'  (paper "User" {paper[0]} {paper[1]})']
    if title:
        out.append(f'  (title_block (title {q(title)}) (comment 1 "Generated by hardware/gen; GPL-3.0-or-later"))')
    out.append("  (lib_symbols")
    for sym, (t, _) in syms.items():
        out.append("    " + t.replace("\n", "\n    "))
    out.append("  )")
    labels, ncs, insts = [], [], []
    # layout: flow parts left to right, wrapping at the page width
    x0, y0 = 30.48, 40.64
    cx, cy, rowh = x0, y0, 0.0
    maxw = paper[0] - 60
    for p in design.parts.values():
        t, pins = syms[p.sym]
        units = sorted({pp["unit"] for pp in pins if pp["unit"] > 0}) or [1]
        for u in units:
            up = [pp for pp in pins if pp["unit"] in (0, u)] if len(units) > 1 else pins
            if not up:
                continue
            xs = [pp["x"] for pp in up]
            ys = [pp["y"] for pp in up]
            w = (max(xs) - min(xs)) + 40.64   # room for labels
            h = (max(ys) - min(ys)) + 10.16
            if cx + w > maxw:
                cx, cy, rowh = x0, cy + rowh + 10.16, 0.0
            ox = round((cx - min(xs) + 15.24) / GRID) * GRID
            oy = round((cy + max(ys) + 5.08) / GRID) * GRID
            cx += w
            rowh = max(rowh, h)
            props = dict(Reference=p.ref, Value=p.value, Footprint=p.footprint or "", Datasheet="")
            ins = [f'  (symbol (lib_id {q(p.sym)}) (at {ox:.2f} {oy:.2f} 0) (unit {u}) (in_bom yes) (on_board yes) (dnp no)',
                   f'    (uuid {uid()})']
            for k, v in props.items():
                hide = " hide" if k in ("Footprint", "Datasheet") else ""
                ins.append(f'    (property {q(k)} {q(v)} (at {ox:.2f} {oy - max(ys) - 3:.2f} 0) (effects (font (size 1.27 1.27)){hide}))')
            for pp in up:
                if pp["number"] in p.pins:
                    ins.append(f'    (pin {q(pp["number"])} (uuid {uid()}))')
                px, py = ox + pp["x"], oy - pp["y"]
                net = p.pins.get(pp["number"], "__missing__")
                if net == "__missing__" or net is None:
                    ncs.append(f'  (no_connect (at {px:.2f} {py:.2f}) (uuid {uid()}))')
                else:
                    ang = {0: 180, 180: 0, 90: 270, 270: 90}[pp["angle"]]
                    just = "right" if ang == 180 else "left"
                    labels.append(f'  (label {q(net)} (at {px:.2f} {py:.2f} {ang}) '
                                  f'(effects (font (size 1.0 1.0)) (justify {just} bottom)) (uuid {uid()}))')
            ins.append(f'    (instances (project "ngsd" (path "/{root}" (reference {q(p.ref)}) (unit {u}))))')
            ins.append("  )")
            insts.append("\n".join(ins))
    out += insts + labels + ncs
    out.append(f'  (sheet_instances (path "/" (page "1")))')
    out.append(")")
    open(path, "w", encoding="utf-8").write("\n".join(out))
